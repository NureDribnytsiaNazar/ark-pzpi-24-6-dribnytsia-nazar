"""Приклади оформлення коду мовою Python за рекомендаціями PEP 8.

Файл супроводжує звіт до практичного завдання № 1 з дисципліни
«Аналіз та рефакторинг коду програмного забезпечення». Лістинги В.1–В.5
повністю відповідають Додатку В звіту. Блоки «Підготовка» не входять до
лістингів і потрібні лише для того, щоб файл виконувався без помилок.

Увага: приклади «Погано» навмисно порушують PEP 8, тому лінтери
(flake8, black) повідомлятимуть про зауваження в цих місцях.

Запуск: python code-examples-code-conventions.py
"""

import logging
from pathlib import Path

logging.basicConfig(level=logging.WARNING)
logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# В.1 Приклад оформлення іменування ідентифікаторів
# ---------------------------------------------------------------------------
# Погано
x = 20
def f(n): ...

# Добре
user_age = 20
def calculate_discount(price):
    ...


# ---------------------------------------------------------------------------
# В.2 Приклад форматування коду
# ---------------------------------------------------------------------------
# Погано
def f(a,b) :
  result=a+b
  return result

# Добре
def f(a, b):
    result = a + b
    return result


# ---------------------------------------------------------------------------
# В.3 Приклад документування функції (docstring, type hints)
# ---------------------------------------------------------------------------
def convert_currency(amount: float, rate: float) -> float:
    """Конвертує суму за заданим курсом.

    Args:
        amount: сума у вихідній валюті.
        rate: курс конвертації.

    Returns:
        Сума у цільовій валюті.
    """
    return amount * rate


# ---------------------------------------------------------------------------
# В.4 Приклад обробки винятків
# ---------------------------------------------------------------------------
# Підготовка (не входить до лістингу)
data = {}
key = "token"

# Погано
try:
    value = data[key]
except:
    pass

# Добре
try:
    value = data[key]
except KeyError:
    logger.warning(f"Ключ {key} відсутній")


# ---------------------------------------------------------------------------
# В.5 Приклад ідіоматичних конструкцій (Pythonic-прийоми)
# ---------------------------------------------------------------------------
# Підготовка (не входить до лістингу)
Path('data.txt').write_text("тестові дані", encoding="utf-8")

# Погано
squares = []
for i in range(10):
    squares.append(i * i)

f = open('data.txt')
text = f.read()
f.close()

# Добре
squares = [i * i for i in range(10)]

with open('data.txt') as f:
    text = f.read()


# Прибирання (не входить до лістингу)
Path('data.txt').unlink()


if __name__ == "__main__":
    print(f"Конвертація: {convert_currency(100.0, 41.5)}")
    print(f"Квадрати: {squares}")
